using Unity.AI.Navigation;
using System.Collections.Generic;
using UnityEngine;
using UnityEngine.AI;

namespace RoadsideHaven
{
    /// <summary>Scene composition root and authoritative owner of motel runtime state.</summary>
    public sealed class MotelGameRoot : MonoBehaviour, IHotelService, IEconomyService
    {
        [Header("Configuration")]
        [Tooltip("Gameplay tuning asset generated by the prototype setup command.")]
        [SerializeField] private HotelGameSettings settings;
        [Tooltip("Baked NavMesh used by all guest agents.")]
        [SerializeField] private NavMeshSurface navigationSurface;
        [Tooltip("Shared material used for spawned guest capsules.")]
        [SerializeField] private Material guestMaterial;
        [Tooltip("Optional meter-scale rigged prefab with Animator and a Speed float parameter. Root motion is disabled.")]
        [SerializeField] private GameObject guestCharacterPrefab;

        [Header("Scene References")]
        [Tooltip("Guest arrival point outside the motel.")]
        [SerializeField] private Transform guestSpawnPoint;
        [Tooltip("Point guests use to leave the property.")]
        [SerializeField] private Transform guestExitPoint;
        [Tooltip("Optional parking-side pedestrian markers. Each must connect to reception on the motel NavMesh.")]
        [SerializeField] private Transform[] parkingArrivalPoints;
        [Tooltip("Distinct reception queue destinations, ordered front to back.")]
        [SerializeField] private Transform[] queuePoints;
        [Tooltip("Generated HUD instance in this scene.")]
        [SerializeField] private MotelHUD hud;
        [Tooltip("Camera controller used to route world taps.")]
        [SerializeField] private IsometricCameraController cameraController;

        private readonly List<HotelRoom> _rooms = new List<HotelRoom>(4);
        private readonly List<RoomSelectable> _roomViews = new List<RoomSelectable>(4);
        private readonly List<GuestSession> _guests = new List<GuestSession>(8);
        private readonly List<GuestActor> _actors = new List<GuestActor>(8);
        private readonly HotelEventHub _events = new HotelEventHub();
        private Wallet _wallet;
        private string _selectedGuestId;
        private string _selectedRoomId;
        private int _nextGuestNumber = 1;
        private float _arrivalTimer;
        private float _snapshotTimer;
        private int _targetFrameRate;
        private int _nextParkingBay;
        private float _rivalAdvertisingPausedUntil;

        public int Coins => _wallet == null ? 0 : _wallet.Coins;
        public bool HasParkingArrivals => parkingArrivalPoints != null && parkingArrivalPoints.Length > 0;

        /// <summary>Spends from the same wallet used for motel checkout payments.</summary>
        public bool TryDebit(int amount)
        {
            if (_wallet == null || !_wallet.TryDebit(amount)) return false;
            PublishSnapshot();
            return true;
        }

        /// <summary>Credits a completed transaction and updates the existing motel HUD.</summary>
        public void Credit(int amount)
        {
            _wallet.Credit(amount);
            PublishSnapshot();
        }

        private void Start()
        {
            // Awake has created the shared wallet before optional scene modules are composed.
            if (enabled && _wallet != null && TryGetComponent<ShopController>(out var shop))
                shop.Initialize(this, cameraController);
        }

        private void Awake()
        {
            if (settings == null || navigationSurface == null || guestSpawnPoint == null ||
                guestExitPoint == null || queuePoints == null || queuePoints.Length == 0)
            {
                Debug.LogError("MotelGameRoot is missing generated scene references.", this);
                enabled = false;
                return;
            }

            _wallet = new Wallet(settings.StartingCoins);
            RoomSelectable[] roomViews = GetComponentsInChildren<RoomSelectable>(true);
            for (int i = 0; i < roomViews.Length; i++)
            {
                RoomSelectable view = roomViews[i];
                _rooms.Add(new HotelRoom(view.RoomId));
                _roomViews.Add(view);
            }
            if (_rooms.Count == 0)
            {
                Debug.LogError("The scene has no generated motel rooms.", this);
                enabled = false;
                return;
            }

            QualitySettings.vSyncCount = 0;
            _targetFrameRate = settings.TargetFrameRate;
            Application.targetFrameRate = _targetFrameRate;
            if (hud == null)
                hud = GetComponentInChildren<MotelHUD>(true);
            if (hud != null)
                hud.Bind(this, _events);
            if (cameraController != null)
                cameraController.Tapped += HandleWorldTap;

            _arrivalTimer = 2f;
            PublishSnapshot();
        }

        private void OnDestroy()
        {
            if (cameraController != null)
                cameraController.Tapped -= HandleWorldTap;
        }

        private void Update()
        {
            float deltaTime = Time.deltaTime;
            _arrivalTimer -= deltaTime;
            if (_arrivalTimer <= 0f)
            {
                _arrivalTimer = settings.GuestArrivalInterval * (Time.time < _rivalAdvertisingPausedUntil ? .75f : 1f);
                TrySpawnGuest();
            }

            for (int i = 0; i < _rooms.Count; i++)
            {
                if (_rooms[i].TickCleaning(deltaTime))
                    _events.Publish(new HotelFeedback($"Room {_rooms[i].Id} is ready."));
            }

            for (int i = _guests.Count - 1; i >= 0; i--)
                TickGuest(i, deltaTime);

            _snapshotTimer += deltaTime;
            if (_snapshotTimer >= 0.5f)
            {
                _snapshotTimer = 0f;
                PublishSnapshot();
            }
        }

        public bool TryAssignGuestToRoom(string guestId, string roomId)
        {
            GuestSession guest = FindGuest(guestId);
            HotelRoom room = FindRoom(roomId);
            RoomSelectable view = FindRoomView(roomId);
            if (guest == null || room == null || view == null || guest.State != GuestState.Waiting ||
                view.EntryPoint == null)
                return false;

            if (!room.TryReserve(guest.Id))
            {
                _events.Publish(new HotelFeedback($"Room {room.Id} is not available."));
                return false;
            }

            GuestActor actor = FindActor(guest.Id);
            if (actor == null || !TrySetDestination(actor.Agent, view.EntryPoint.position))
            {
                room.ReleaseReservation(guest.Id);
                _events.Publish(new HotelFeedback("That guest cannot reach the room. Try another room."));
                return false;
            }

            guest.RoomId = room.Id;
            guest.QueueSlot = -1;
            guest.State = GuestState.ToRoom;
            guest.NavigationDeadline = Time.time + settings.NavigationTimeoutSeconds;
            _selectedGuestId = null;
            _selectedRoomId = room.Id;
            _events.Publish(new HotelFeedback($"Guest {guest.Id} is heading to room {room.Id}."));
            PublishSnapshot();
            return true;
        }

        /// <summary>Fictional rival advertising outage briefly diverts more arrivals to this motel.</summary>
        public void PauseRivalAdvertising(float seconds)
        { _rivalAdvertisingPausedUntil = Time.time + Mathf.Clamp(seconds, 0, 120); }

        public bool TryOwnerCheckIn(Vector3 ownerPosition, float radius)
        {
            for (int guestIndex = 0; guestIndex < _guests.Count; guestIndex++)
            {
                if (_guests[guestIndex].State != GuestState.Waiting || _actors[guestIndex] == null ||
                    Vector3.Distance(ownerPosition, _actors[guestIndex].transform.position) > radius) continue;
                for (int roomIndex = 0; roomIndex < _rooms.Count; roomIndex++)
                    if (_rooms[roomIndex].State == RoomState.Available &&
                        TryAssignGuestToRoom(_guests[guestIndex].Id, _rooms[roomIndex].Id)) return true;
            }
            return false;
        }
        public bool TryOwnerCleanNearest(Vector3 ownerPosition, float radius)
        {
            for (int i = 0; i < _rooms.Count; i++)
            {
                var entry = _roomViews[i].EntryPoint;
                if (_rooms[i].State == RoomState.Dirty && entry != null &&
                    Vector3.Distance(ownerPosition, entry.position) <= radius)
                    return TryBeginCleaning(_rooms[i].Id);
            }
            return false;
        }
        public bool TryBeginCleaning(string roomId)
        {
            HotelRoom room = FindRoom(roomId);
            if (room == null || !room.TryStartCleaning(settings.CleaningSeconds))
            {
                _events.Publish(new HotelFeedback("Only dirty rooms can be cleaned."));
                return false;
            }

            _events.Publish(new HotelFeedback($"Cleaning room {room.Id}..."));
            PublishSnapshot();
            return true;
        }

        private void TrySpawnGuest()
        {
            if (_guests.Count >= settings.MaximumGuests || guestSpawnPoint == null ||
                guestExitPoint == null || queuePoints == null)
                return;

            int queueSlot = FindFreeQueueSlot();
            if (queueSlot < 0)
                return;
            int parkingBay = -1;
            Vector3 spawnPosition = guestSpawnPoint.position;
            if (parkingArrivalPoints != null && parkingArrivalPoints.Length > 0)
            {
                parkingBay = FindReachableParkingBay(queuePoints[queueSlot].position, out spawnPosition);
                if (parkingBay < 0) return;
            }
            if (!NavMesh.SamplePosition(spawnPosition, out NavMeshHit hit, .7f, NavMesh.AllAreas))
            {
                Debug.LogWarning("Guest spawn point is not near the baked NavMesh.", guestSpawnPoint);
                return;
            }

            string guestId = $"G{_nextGuestNumber:000}";
            GameObject guestObject = new GameObject();
            GameObject body = GameObject.CreatePrimitive(PrimitiveType.Capsule);
            body.transform.SetParent(guestObject.transform, false);
            body.transform.localPosition = Vector3.up * 0.8f;
            guestObject.name = $"Guest {guestId}";
            guestObject.transform.position = hit.position;
            body.transform.localScale = new Vector3(0.65f, 0.8f, 0.65f);
            if (guestMaterial != null)
                body.GetComponent<Renderer>().sharedMaterial = guestMaterial;
            NavMeshAgent agent = guestObject.AddComponent<NavMeshAgent>();
            agent.radius = 0.28f;
            agent.height = 1.5f;
            agent.speed = 2.6f;
            agent.acceleration = 8f;
            agent.angularSpeed = 540f;
            agent.stoppingDistance = 0.18f;
            agent.obstacleAvoidanceType = ObstacleAvoidanceType.MedQualityObstacleAvoidance;
            GuestSelectable selectable = guestObject.AddComponent<GuestSelectable>();
            selectable.Configure(guestId);
            GuestActor actor = guestObject.AddComponent<GuestActor>();
            guestObject.GetComponent<ProceduralWalker>().ConfigureVisual(guestCharacterPrefab);
            if (!agent.isOnNavMesh || !TrySetDestination(agent, queuePoints[queueSlot].position))
            {
                Destroy(guestObject);
                return;
            }

            GuestSession guest = new GuestSession(guestId, GuestState.ToReception)
            {
                QueueSlot = queueSlot,
                ParkingBay = parkingBay,
                NavigationDeadline = Time.time + settings.NavigationTimeoutSeconds
            };
            _nextGuestNumber++;
            _guests.Add(guest);
            _actors.Add(actor);
            if (parkingBay >= 0)
            {
                _nextParkingBay = (parkingBay + 1) % parkingArrivalPoints.Length;
                _events.Publish(new HotelFeedback($"Guest {guestId} arrived from parking. Walking to reception."));
            }
            PublishSnapshot();
        }

        private int FindReachableParkingBay(Vector3 reception, out Vector3 position)
        {
            position = guestSpawnPoint.position;
            if (!NavMesh.SamplePosition(reception, out var target, .7f, NavMesh.AllAreas)) return -1;
            var path = new NavMeshPath();
            for (int offset = 0; offset < parkingArrivalPoints.Length; offset++)
            {
                int index = (_nextParkingBay + offset) % parkingArrivalPoints.Length;
                var marker = parkingArrivalPoints[index];
                if (marker == null || !NavMesh.SamplePosition(marker.position, out var origin, .7f, NavMesh.AllAreas)) continue;
                bool blocked = false;
                for (int i = 0; i < _actors.Count; i++)
                    if (_actors[i] != null && (_actors[i].transform.position - origin.position).sqrMagnitude < 1f)
                    { blocked = true; break; }
                if (blocked || !NavMesh.CalculatePath(origin.position, target.position, NavMesh.AllAreas, path) ||
                    path.status != NavMeshPathStatus.PathComplete) continue;
                position = origin.position;
                return index;
            }
            return -1;
        }

        private void TickGuest(int index, float deltaTime)
        {
            GuestSession guest = _guests[index];
            GuestActor actor = _actors[index];
            if (actor == null || actor.Agent == null)
            {
                RemoveGuestAt(index, false);
                return;
            }

            if (guest.State == GuestState.Waiting)
            {
                guest.PatienceRemaining -= deltaTime;
                if (guest.PatienceRemaining <= 0f)
                {
                    _events.Publish(new HotelFeedback($"Guest {guest.Id} ran out of patience and left."));
                    BeginLeaving(guest, actor);
                }
                return;
            }

            if (guest.State == GuestState.Staying)
            {
                guest.StayRemaining -= deltaTime;
                if (guest.StayRemaining <= 0f)
                {
                    HotelRoom room = FindRoom(guest.RoomId);
                    if (room != null && room.TryCheckOut(guest, _wallet, settings.RoomRate))
                    {
                        _events.Publish(new HotelFeedback($"Guest checked out. +{settings.RoomRate} coins; room is dirty."));
                        guest.RoomId = null;
                        BeginLeaving(guest, actor);
                        PublishSnapshot();
                    }
                    else
                    {
                        Debug.LogError($"Could not settle checkout for guest {guest.Id}.", this);
                        BeginLeaving(guest, actor);
                    }
                }
                return;
            }

            if (guest.State == GuestState.Leaving)
            {
                if (HasArrived(actor.Agent) || Time.time >= guest.NavigationDeadline)
                    RemoveGuestAt(index, true);
                return;
            }

            if (Time.time >= guest.NavigationDeadline)
            {
                HandleNavigationFailure(guest, actor);
                return;
            }

            if (actor.Agent.pathPending)
                return;
            if (actor.Agent.pathStatus == NavMeshPathStatus.PathInvalid)
            {
                HandleNavigationFailure(guest, actor);
                return;
            }

            if (!HasArrived(actor.Agent))
                return;

            if (guest.State == GuestState.ToReception)
            {
                guest.State = GuestState.Waiting;
                guest.PatienceRemaining = settings.GuestPatienceSeconds;
                _events.Publish(new HotelFeedback($"Guest {guest.Id} is waiting at reception."));
                PublishSnapshot();
            }
            else if (guest.State == GuestState.ToRoom)
            {
                HotelRoom room = FindRoom(guest.RoomId);
                if (room != null && room.TryMarkOccupied(guest.Id))
                {
                    guest.State = GuestState.Staying;
                    guest.StayRemaining = settings.GuestStaySeconds;
                    _events.Publish(new HotelFeedback($"Guest {guest.Id} checked into room {room.Id}."));
                    PublishSnapshot();
                }
                else
                {
                    Debug.LogError($"Room reservation for guest {guest.Id} was lost.", this);
                    BeginLeaving(guest, actor);
                }
            }
        }

        private void HandleNavigationFailure(GuestSession guest, GuestActor actor)
        {
            if (guest.State == GuestState.ToRoom && !string.IsNullOrEmpty(guest.RoomId))
            {
                HotelRoom room = FindRoom(guest.RoomId);
                room?.ReleaseReservation(guest.Id);
                guest.RoomId = null;
            }
            _events.Publish(new HotelFeedback($"Guest {guest.Id} could not find a path and left."));
            BeginLeaving(guest, actor);
            PublishSnapshot();
        }

        private void BeginLeaving(GuestSession guest, GuestActor actor)
        {
            guest.State = GuestState.Leaving;
            guest.QueueSlot = -1;
            guest.NavigationDeadline = Time.time + settings.NavigationTimeoutSeconds;
            Vector3 exitPosition = guestExitPoint.position;
            if (parkingArrivalPoints != null && guest.ParkingBay >= 0 && guest.ParkingBay < parkingArrivalPoints.Length &&
                parkingArrivalPoints[guest.ParkingBay] != null)
                exitPosition = parkingArrivalPoints[guest.ParkingBay].position;
            if (actor.Agent != null && actor.Agent.isOnNavMesh &&
                TrySetDestination(actor.Agent, exitPosition))
                return;

            guest.NavigationDeadline = Time.time + 0.5f;
        }

        private void RemoveGuestAt(int index, bool repackQueue)
        {
            GuestSession guest = _guests[index];
            GuestActor actor = _actors[index];
            if (!string.IsNullOrEmpty(guest.RoomId)) FindRoom(guest.RoomId)?.ReleaseReservation(guest.Id);
            _guests.RemoveAt(index);
            _actors.RemoveAt(index);
            if (actor != null)
                Destroy(actor.gameObject);
            if (_selectedGuestId == guest.Id)
                _selectedGuestId = null;

            PublishSnapshot();
        }

        private int FindFreeQueueSlot()
        {
            for (int slot = 0; slot < queuePoints.Length; slot++)
            {
                bool occupied = false;
                for (int i = 0; i < _guests.Count; i++)
                {
                    if (_guests[i].QueueSlot == slot &&
                        (_guests[i].State == GuestState.ToReception || _guests[i].State == GuestState.Waiting))
                    {
                        occupied = true;
                        break;
                    }
                }
                if (!occupied)
                    return slot;
            }
            return -1;
        }

        private static bool TrySetDestination(NavMeshAgent agent, Vector3 destination)
        {
            if (agent == null || !agent.isOnNavMesh ||
                !NavMesh.SamplePosition(destination, out NavMeshHit hit, 2f, NavMesh.AllAreas))
                return false;
            var path = new NavMeshPath();
            if (!agent.CalculatePath(hit.position, path) || path.status != NavMeshPathStatus.PathComplete) return false;
            return agent.SetPath(path);
        }

        private static bool HasArrived(NavMeshAgent agent)
        {
            return agent != null && agent.isOnNavMesh && !agent.pathPending &&
                   agent.pathStatus == NavMeshPathStatus.PathComplete &&
                   agent.remainingDistance <= agent.stoppingDistance + 0.15f;
        }

        private void HandleWorldTap(Vector2 screenPosition)
        {
            Camera camera = cameraController.GetComponent<Camera>();
            Ray ray = camera.ScreenPointToRay(screenPosition);
            if (!Physics.Raycast(ray, out RaycastHit hit, 100f))
                return;

            GuestSelectable guest = hit.collider.GetComponentInParent<GuestSelectable>();
            if (guest != null)
            {
                GuestSession session = FindGuest(guest.GuestId);
                if (session != null && session.State == GuestState.Waiting)
                {
                    _selectedGuestId = session.Id;
                    _selectedRoomId = null;
                    _events.Publish(new HotelFeedback($"Guest {session.Id} selected. Tap an available room."));
                    PublishSnapshot();
                }
                return;
            }

            RoomSelectable roomView = hit.collider.GetComponentInParent<RoomSelectable>();
            if (roomView == null)
                return;
            HotelRoom room = FindRoom(roomView.RoomId);
            if (room == null)
                return;
            if (!string.IsNullOrEmpty(_selectedGuestId) && room.State == RoomState.Available)
            {
                TryAssignGuestToRoom(_selectedGuestId, room.Id);
                return;
            }

            _selectedRoomId = room.Id;
            _selectedGuestId = null;
            _events.Publish(new HotelFeedback($"Room {room.Id}: {room.State}."));
            PublishSnapshot();
        }

        private void PublishSnapshot()
        {
            if (_wallet == null)
                return;
            int occupied = 0;
            int waiting = 0;
            int available = 0;
            int dirty = 0;
            int cleaning = 0;
            int reserved = 0;
            for (int i = 0; i < _rooms.Count; i++)
            {
                if (_rooms[i].State == RoomState.Occupied)
                    occupied++;
                else if (_rooms[i].State == RoomState.Available) available++;
                else if (_rooms[i].State == RoomState.Dirty) dirty++;
                else if (_rooms[i].State == RoomState.Cleaning) cleaning++;
                else if (_rooms[i].State == RoomState.Reserved) reserved++;

                GuestSession occupant = FindGuest(_rooms[i].GuestId);
                _roomViews[i].RefreshStatus(_rooms[i], _rooms[i].Id == _selectedRoomId,
                    occupant == null ? 0f : occupant.StayRemaining);
            }
            for (int i = 0; i < _guests.Count; i++)
                if (_guests[i].State == GuestState.Waiting)
                    waiting++;

            string details = "Select a waiting guest or room.";
            if (!string.IsNullOrEmpty(_selectedGuestId))
            {
                GuestSession guest = FindGuest(_selectedGuestId);
                if (guest != null)
                    details = $"Guest {guest.Id} | Patience {Mathf.CeilToInt(guest.PatienceRemaining)}s | Tap an available room";
            }
            else if (!string.IsNullOrEmpty(_selectedRoomId))
            {
                HotelRoom room = FindRoom(_selectedRoomId);
                if (room != null)
                    details = $"Room {room.Id} | {room.State}" +
                              (room.State == RoomState.Cleaning
                                  ? $" ({Mathf.CeilToInt(room.CleaningRemaining)}s remaining)"
                                  : room.State == RoomState.Occupied && FindGuest(room.GuestId) != null
                                      ? $" ({Mathf.CeilToInt(FindGuest(room.GuestId).StayRemaining)}s to checkout)"
                                  : string.Empty);
            }

            HotelRoom selectedRoom = FindRoom(_selectedRoomId);
            _events.Publish(new HotelSnapshot(_wallet.Coins, occupied, _rooms.Count, waiting,
                details, selectedRoom != null && selectedRoom.State == RoomState.Dirty, _selectedRoomId,
                $"READY {available}  |  RESERVED {reserved}  |  DIRTY {dirty}  |  CLEANING {cleaning}"));
        }

        private HotelRoom FindRoom(string id)
        {
            for (int i = 0; i < _rooms.Count; i++)
                if (_rooms[i].Id == id)
                    return _rooms[i];
            return null;
        }

        private RoomSelectable FindRoomView(string id)
        {
            for (int i = 0; i < _roomViews.Count; i++)
                if (_roomViews[i].RoomId == id)
                    return _roomViews[i];
            return null;
        }

        private GuestSession FindGuest(string id)
        {
            for (int i = 0; i < _guests.Count; i++)
                if (_guests[i].Id == id)
                    return _guests[i];
            return null;
        }

        private GuestActor FindActor(string guestId)
        {
            for (int i = 0; i < _guests.Count; i++)
                if (_guests[i].Id == guestId)
                    return _actors[i];
            return null;
        }

        /// <summary>Called by the generated Editor scene builder to wire scene references.</summary>
        public void ConfigureParkingArrivals(Transform[] pedestrianMarkers)
        {
            parkingArrivalPoints = pedestrianMarkers;
        }

        /// <summary>Called by the generated Editor scene builder to wire scene references.</summary>
        public void Configure(HotelGameSettings gameSettings, NavMeshSurface surface, Transform spawn,
            Transform exit, Transform[] queue, Material guestVisualMaterial, MotelHUD gameHud,
            IsometricCameraController camera)
        {
            settings = gameSettings;
            navigationSurface = surface;
            guestMaterial = guestVisualMaterial;
            guestSpawnPoint = spawn;
            guestExitPoint = exit;
            queuePoints = queue;
            hud = gameHud;
            cameraController = camera;
        }
    }
}



